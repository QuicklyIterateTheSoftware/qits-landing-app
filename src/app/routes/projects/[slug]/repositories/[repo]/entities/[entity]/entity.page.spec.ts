import type { HttpTestingController } from '@angular/common/http/testing';
import { QITS_MERMAID_LOADER, type QitsMermaid } from '@qits/ui-components';
import { client as artifactsClient } from '../../../../../../../api/artifacts/client.gen';
import { provideHeyApiClient } from '../../../../../../../api/artifacts/client/client.gen';
import { literalDocsPaths } from '$core/ui-builder/docs-paths';
import type { GoldenIndex } from '$core/ui-builder/golden-masters.store';
import {
  artifactsGoldenMasters as masters,
  projectsGoldenIndex,
} from '../../../../../../../../testing/golden-masters';
import {
  configureContractsPage,
  CONTRACTS,
  openContractsPage,
  REPO,
  SLUG,
  text,
  VERSION,
  versionsAt,
} from '../../../../../../../../testing/contracts-pages';
import { EntityPage } from './entity.page';

/**
 * An entity's page against qits-artifacts' recorded entity map of `@contracts/qits-projects`
 * (Project, Repository and WorkEntity domain, LegacyPlacement technical), and qits-projects' own
 * published index (its golden-masters package) for the states each operation is recorded in.
 * The recorded map holds no projection: that case marks the recorded Repository a projection of
 * `qits-projects:Project`, which then resolves inside the same bundle.
 *
 * The ER diagram (qits-2014): no recording of qits-artifacts holds a bundle's `database/` files
 * yet, so the index and the diagram file are written here in the shape `qits database diagram`
 * publishes them (qits-projects-service's `docs/database/`), its unit holding the recorded Project
 * and LegacyPlacement. mermaid is a stub that draws a marked `<svg>`.
 */
interface RecordedMap {
  entities: { entity: string; marking: string; projectionOf: string | null }[];
}
const MAP = masters.body<RecordedMap>(CONTRACTS, 'getDocsFile');
const INDEX = projectsGoldenIndex<GoldenIndex>();
const PROJECT = 'eu.wohlben.qits.entities.domain.Project';
const REPOSITORY = 'eu.wohlben.qits.entities.domain.Repository';
const LEGACY = 'eu.wohlben.qits.entities.domain.LegacyPlacement';

const DATABASE_INDEX = {
  formatVersion: 1,
  units: [
    {
      unit: 'projects',
      file: 'projects.md',
      entities: [
        { entity: PROJECT, table: 'project' },
        { entity: LEGACY, table: 'legacy_placement' },
      ],
    },
  ],
};
const DEFINITION = [
  'erDiagram',
  '  %% Project: eu.wohlben.qits.entities.domain.Project (projects)',
  '  project {',
  '    uuid id PK "not null"',
  '    string name "not null"',
  '  }',
].join('\n');
const DIAGRAM_FILE = [
  '<!-- Generated by `qits database diagram` (jpa). Do not edit. -->',
  '# Persistence unit `projects`',
  '',
  '```mermaid',
  DEFINITION,
  '```',
  '',
].join('\n');

/**
 * What mermaid draws for an `erDiagram`, cut down: a 1200×800 viewBox it fits to its width, and
 * each table's group named `<id>-entity-<table>-<n>`; `project_member` is there to show the match
 * is the whole table name.
 */
const drawn = (id: string) =>
  `<svg class="drawn" width="100%" style="max-width: 1200px;" viewBox="0 0 1200 800">` +
  `<g id="${id}-entity-project_member-1"></g><g id="${id}-entity-project-2"></g></svg>`;

const mermaid = {
  initialize: vi.fn(),
  render: vi.fn(async (id: string) => ({ svg: drawn(id) })),
} satisfies QitsMermaid;

type Rect = Pick<DOMRect, 'left' | 'top' | 'width' | 'height'>;

/**
 * jsdom lays nothing out, so the box and the groups are given rectangles: the box 400×300 at
 * (100, 50), every group 200×100 at (900, 500) as the box shows it unscrolled.
 */
function layOut(): void {
  const box: Rect = { left: 100, top: 50, width: 400, height: 300 };
  const group: Rect = { left: 900, top: 500, width: 200, height: 100 };
  const of = (element: Element) =>
    element.classList.contains('diagram-box') ? box : element.localName === 'g' ? group : null;
  vi.spyOn(Element.prototype, 'getBoundingClientRect').mockImplementation(function (this: Element) {
    const rect = of(this) ?? { left: 0, top: 0, width: 0, height: 0 };
    return { ...rect, x: rect.left, y: rect.top, right: 0, bottom: 0, toJSON: () => rect };
  });
  vi.spyOn(Element.prototype, 'clientWidth', 'get').mockImplementation(function (this: Element) {
    return of(this)?.width ?? 0;
  });
  vi.spyOn(Element.prototype, 'clientHeight', 'get').mockImplementation(function (this: Element) {
    return of(this)?.height ?? 0;
  });
}

describe('EntityPage', () => {
  let http: HttpTestingController;

  beforeEach(() => {
    http = configureContractsPage(
      'projects/:slug/repositories/:repo/entities/:entity',
      EntityPage,
      [
        provideHeyApiClient(artifactsClient),
        { provide: QITS_MERMAID_LOADER, useValue: async () => mermaid },
      ],
    );
    mermaid.render.mockClear();
    if (!artifactsClient.interceptors.request.exists(literalDocsPaths)) {
      artifactsClient.interceptors.request.use(literalDocsPaths);
    }
  });

  afterEach(() => {
    vi.restoreAllMocks();
    http.verify();
  });

  const url = (entity: string) => `/projects/${SLUG}/repositories/${REPO}/entities/${entity}`;

  it('shows a domain entity’s DTOs and operations, each kind explained, with their states', async () => {
    const { element, answer } = await openContractsPage(http, url(PROJECT));
    await answer('entities.json', MAP);
    await answer('golden-masters/index.json', INDEX);
    await answer('database/index.json', null, undefined, 404);

    expect(text(element.querySelector('h1'))).toBe('Project');
    expect(text(element.querySelector('.fqn'))).toBe(PROJECT);
    expect(text(element.querySelector('.marking'))).toBe('domain');
    expect(element.querySelector('.reason')).toBeNull();
    const dto = element.querySelector('.dto')!;
    expect(text(dto)).toContain('eu.wohlben.qits.entities.dto.ProjectDto mapper');
    expect(text(dto.querySelector('.note'))).toContain('taking the entity as a parameter');
    expect(text(dto)).toContain('ProjectMapper.toDto(Project)');
    const ops = [...element.querySelectorAll('.operation')];
    expect(ops.map((op) => text(op.querySelector('p')))).toEqual([
      'getProject GET /projects/{projectId} returns',
      'listProjects GET /projects returns',
    ]);
    expect(text(ops[1].querySelector('.note'))).toContain('return type');
    const states = [...ops[1].querySelectorAll('.states a')];
    expect(states.map((a) => text(a))).toContain('a project exists');
    expect(states.find((a) => text(a) === 'a project exists')?.getAttribute('href')).toBe(
      `/projects/${SLUG}/repositories/${REPO}/contracts/a-project-exists`,
    );
  });

  it('shows why a technical entity is one', async () => {
    const { element, answer } = await openContractsPage(http, url(LEGACY));
    await answer('entities.json', MAP);
    await answer('golden-masters/index.json', INDEX);
    await answer('database/index.json', null, undefined, 404);
    expect(text(element.querySelector('h1'))).toBe('LegacyPlacement');
    expect(text(element.querySelector('.reason'))).toBe('bookkeeping of a retired layout');
    expect(text(element)).toContain('No operation hands it out.');
  });

  it('links a projection to the entity it projects', async () => {
    // Its own version, so its map is read here and not found cached.
    const { element, answer } = await openContractsPage(
      http,
      url(REPOSITORY),
      versionsAt('2100.1.2'),
    );
    const projected = {
      ...MAP,
      entities: MAP.entities.map((e) =>
        e.entity === REPOSITORY
          ? { ...e, marking: 'projection', projectionOf: 'qits-projects:Project' }
          : e,
      ),
    };
    await answer('entities.json', projected, '2100.1.2');
    await answer('golden-masters/index.json', null, '2100.1.2', 404);
    await answer('database/index.json', null, '2100.1.2', 404);
    const projection = element.querySelector('.projection a');
    expect(text(projection)).toBe('qits-projects:Project');
    expect(projection?.getAttribute('href')).toBe(
      `/projects/${SLUG}/repositories/${REPO}/entities/${PROJECT}`,
    );
    expect(text(element)).toContain('Could not read the golden masters');
  });

  it('says so for a class the map does not list', async () => {
    const { element, answer } = await openContractsPage(http, url('a.NoSuchEntity'));
    await answer('entities.json', MAP);
    await answer('golden-masters/index.json', INDEX);
    await answer('database/index.json', DATABASE_INDEX);
    expect(text(element.querySelector('.unknown'))).toBe(
      `No such entity in qits-projects ${VERSION}. All entities`,
    );
    expect(element.querySelector('.er-diagram')).toBeNull();
  });

  it('draws the ER diagram of the unit holding the entity', async () => {
    const { element, answer } = await openContractsPage(http, url(PROJECT));
    await answer('entities.json', MAP);
    await answer('golden-masters/index.json', INDEX);
    await answer('database/index.json', DATABASE_INDEX);
    await answer('database/projects.md', DIAGRAM_FILE);

    const section = element.querySelector('.er-diagram')!;
    expect(text(section.querySelector('.unit'))).toBe('Persistence unit projects');
    expect(mermaid.render).toHaveBeenCalledWith(expect.any(String), DEFINITION);
    expect(section.querySelector('qits-mermaid-diagram svg.drawn')).not.toBeNull();
    expect(
      section.querySelector('qits-mermaid-diagram [role="img"]')?.getAttribute('aria-label'),
    ).toBe('ER diagram of the persistence unit projects');
    expect(section.querySelector('.no-diagram')).toBeNull();
  });

  it('draws the ER diagram at its natural size, scrolled to the entity’s table', async () => {
    layOut();
    const { element, answer } = await openContractsPage(http, url(PROJECT));
    await answer('entities.json', MAP);
    await answer('golden-masters/index.json', INDEX);
    await answer('database/index.json', DATABASE_INDEX);
    await answer('database/projects.md', DIAGRAM_FILE);

    const box = element.querySelector<HTMLElement>('.er-diagram .diagram-box')!;
    const svg = box.querySelector<SVGSVGElement>('svg.drawn')!;
    expect(svg.style.width).toBe('1200px');
    expect(svg.style.height).toBe('800px');
    expect(svg.style.maxWidth).toBe('none');
    // `project`'s group, not `project_member`'s (whose rectangle is the same): its centre in the
    // box's content, (900 - 100 + 100, 500 - 50 + 50), less half the 400×300 box.
    expect(svg.querySelector('g[id$="-entity-project-2"]')).not.toBeNull();
    expect(box.scrollLeft).toBe(900 - 100 + 100 - 200);
    expect(box.scrollTop).toBe(500 - 50 + 50 - 150);
  });

  it('leaves the ER diagram at the top-left when it draws no box for the entity’s table', async () => {
    layOut();
    const { element, answer } = await openContractsPage(http, url(LEGACY), versionsAt('2100.1.3'));
    await answer('entities.json', MAP, '2100.1.3');
    await answer('golden-masters/index.json', INDEX, '2100.1.3');
    await answer('database/index.json', DATABASE_INDEX, '2100.1.3');
    await answer('database/projects.md', DIAGRAM_FILE, '2100.1.3');

    const box = element.querySelector<HTMLElement>('.er-diagram .diagram-box')!;
    expect(box.querySelector<SVGSVGElement>('svg.drawn')?.style.width).toBe('1200px');
    expect(box.scrollLeft).toBe(0);
    expect(box.scrollTop).toBe(0);
  });

  it('says no ER diagram is published when the bundle has no database index', async () => {
    const { element, answer } = await openContractsPage(http, url(PROJECT));
    await answer('entities.json', MAP);
    await answer('golden-masters/index.json', INDEX);
    await answer('database/index.json', null, undefined, 404);

    expect(text(element.querySelector('.er-diagram .no-diagram'))).toBe(
      'No ER diagram published for this entity.',
    );
    expect(element.querySelector('.diagram-error')).toBeNull();
    expect(mermaid.render).not.toHaveBeenCalled();
  });

  it('says no ER diagram is published when no unit holds the entity', async () => {
    const { element, answer } = await openContractsPage(http, url(REPOSITORY));
    await answer('entities.json', MAP);
    await answer('golden-masters/index.json', INDEX);
    await answer('database/index.json', DATABASE_INDEX);

    expect(text(element.querySelector('.er-diagram .no-diagram'))).toBe(
      'No ER diagram published for this entity.',
    );
    expect(mermaid.render).not.toHaveBeenCalled();
  });

  it('says so when the database index cannot be read', async () => {
    const { element, answer } = await openContractsPage(http, url(PROJECT));
    await answer('entities.json', MAP);
    await answer('golden-masters/index.json', INDEX);
    await answer('database/index.json', null, undefined, 500);

    expect(text(element.querySelector('.er-diagram .diagram-error'))).toBe(
      'Could not read the ER diagram.',
    );
    expect(element.querySelector('.no-diagram')).toBeNull();
  });
});
